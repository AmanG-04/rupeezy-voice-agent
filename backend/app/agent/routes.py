"""HTTP routes for the conversation engine.

Phase 2 surface:
  POST /api/conversations            -> create a new conversation
  GET  /api/conversations/{id}       -> read transcript + status
  POST /api/conversations/{id}/turn  -> SSE stream of agent reply tokens
  POST /api/conversations/{id}/end   -> mark conversation ended
"""

from __future__ import annotations

import asyncio
import json
import logging
from collections.abc import AsyncIterator

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field
from sse_starlette.sse import EventSourceResponse


from app.agent.conversation import (
    Conversation,
    get_store,
    stream_user_turn,
)
from app.scoring.handoff import build_handoff
from app.scoring.schemas import HandoffRecord
from app.agent.locks import conversation_lock
from app.agent.settings import AgentSettings

log = logging.getLogger("rupeezy.agent.routes")

router = APIRouter(prefix="/api/conversations", tags=["agent"])


# ---------- DTOs ----------


class CreateConversationRequest(BaseModel):
    """Optional body for POST /api/conversations.

    When `lead_id` is present, the engine binds the conversation to that lead
    and the system-prompt builder pulls cross-call memory from prior completed
    calls of the same lead (Phase 10).
    """

    lead_id: str | None = None
    settings: AgentSettings = Field(default_factory=AgentSettings)


class CreateConversationResponse(BaseModel):
    conv_id: str
    started_at: str
    lead_id: str | None = None


class TurnRequest(BaseModel):
    text: str = Field(..., min_length=1, max_length=4000)
    # Optional language hint from the frontend voice/chat picker. When set,
    # tells the agent to reply in this language regardless of what the
    # user's text is in. Critical for romanised regional words ("Bhalobashi"
    # could be Bengali or just Latin gibberish — the picker disambiguates).
    # Accepts BCP-47 codes ("bn-IN", "en-IN") or short keys ("bengali",
    # "english"). Empty / unrecognised falls through to language detection.
    lang: str | None = Field(default=None, max_length=20)


class OpenerRequest(BaseModel):
    lang: str | None = Field(default=None, max_length=20)


class EndRequest(BaseModel):
    ended_by: str = Field(default="agent", pattern="^(agent|lead|dropped)$")


class MessageDTO(BaseModel):
    role: str
    text: str
    created_at: str


class ConversationDTO(BaseModel):
    conv_id: str
    started_at: str
    ended_at: str | None
    ended_by: str | None
    language: str
    messages: list[MessageDTO]


def _to_dto(conv: Conversation) -> ConversationDTO:
    return ConversationDTO(
        conv_id=conv.conv_id,
        started_at=conv.started_at,
        ended_at=conv.ended_at,
        ended_by=conv.ended_by,
        language=conv.language,
        messages=[MessageDTO(role=m.role, text=m.text, created_at=m.created_at) for m in conv.messages],
    )


def _row_to_dto(row) -> ConversationDTO:  # type: ignore[no-untyped-def]
    """Convert a SQLAlchemy ConversationRow to the wire DTO."""
    return ConversationDTO(
        conv_id=row.id,
        started_at=row.started_at.isoformat() if row.started_at else "",
        ended_at=row.ended_at.isoformat() if row.ended_at else None,
        ended_by=row.ended_by,
        language=row.language_used,
        messages=[
            MessageDTO(
                role=m.role,
                text=m.text,
                created_at=m.created_at.isoformat() if m.created_at else "",
            )
            for m in row.messages
        ],
    )


