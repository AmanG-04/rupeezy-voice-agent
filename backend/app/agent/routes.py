def _opener_for_lang(lang: str | None) -> str:
    key = (lang or "en").strip().lower().split("-")[0]
    if key in ("hinglish", "hindi"):
        key = "hi"
    return _OPENER_BY_LANG.get(key, _OPENER_BY_LANG["en"])


